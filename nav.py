# rebuilds the site sidebar from index.md
import json, re
from pathlib import Path

MARK = "# --- generated by nav.py ---"

for f in Path("nav").glob("*.md"):
    f.unlink()
Path("nav").mkdir(exist_ok=True)

pages = [("", {"layout": "default"}), ("index.md", {"nav_exclude": True})]
n = sub = 0
section = None

for line in Path("index.md").read_text(encoding="utf-8").splitlines():
    m = re.match(r"^( *)- (?:\[(.+?)\]\((.+?)\)|(.+?))\s*$", line)
    if not m:
        continue
    indent, title, path, heading = m.groups()

    if indent:
        sub += 1
        pages.append((path, {"title": title, "parent": section, "nav_order": sub}))
        continue

    n += 1
    sub = 0
    section = heading
    if heading:
        title = heading
        path = "nav/" + re.sub(r"[^a-z0-9]+", "-", heading.lower()).strip("-") + ".md"
        Path(path).write_text("---\n---\n", encoding="utf-8")
    pages.append((path, {"title": title, "nav_order": n}))

out = [MARK, "defaults:"]
for path, vals in pages:
    out.append(f"  - scope: {{path: {json.dumps(path)}}}")
    out.append("    values:")
    for k, v in vals.items():
        out.append(f"      {k}: {json.dumps(v)}")

cfg = Path("_config.yml")
top = cfg.read_text(encoding="utf-8").split(MARK)[0].rstrip()
cfg.write_text(top + "\n\n" + "\n".join(out) + "\n", encoding="utf-8")
